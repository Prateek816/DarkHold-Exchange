// Generates generated/types.ts from schemas/*.json. CI fails if regenerating changes the committed file.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(root, "schemas");
const files = readdirSync(schemaDir).filter((f) => f.endsWith(".schema.json")).sort();

let out = "/* AUTO-GENERATED by contracts/scripts/generate-types.mjs from contracts/schemas. DO NOT EDIT. */\n\n";
for (const f of files) {
  const schema = JSON.parse(readFileSync(join(schemaDir, f), "utf8"));
  const ts = await compile(schema, schema.title ?? f, {
    bannerComment: "",
    additionalProperties: false,
    cwd: schemaDir,
    format: true,
  });
  out += `// ---- ${f} ----\n${ts.trim()}\n\n`;
}
writeFileSync(join(root, "generated/types.ts"), out.trimEnd() + "\n");
console.log(`generated/types.ts written from ${files.length} schemas`);
